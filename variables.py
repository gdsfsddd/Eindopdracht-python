
# Producten in de winkel
product_1 = "Laptop"
product_2 = "Muis"
product_3 = "Toetsenbord"

# Prijzen van de producten
price_1 = 800
price_2 = 25
price_3 = 50

# Aantal verkochte producten
quantity_1 = 2
quantity_2 = 10
quantity_3 = 5

# Bereken de totale omzet
total_revenue = (
    price_1 * quantity_1
    + price_2 * quantity_2
    + price_3 * quantity_3
)

# Print de producten
print(product_1, price_1, quantity_1)
print(product_2, price_2, quantity_2)
print(product_3, price_3, quantity_3)

# Print de totale omzet
print("Totale omzet:", total_revenue)
